-- مراحل:
-- ۱) ابتدا در خودِ سایت با ایمیل و رمز دلخواه «ثبت‌نام» کنید
--    (اگر Supabase ایمیل تأیید فرستاد، آن را تأیید کنید).
-- ۲) در خط زیر، عبارت  your-email@example.com  را با همان ایمیل جایگزین کنید.
-- ۳) این فایل را در Supabase > SQL Editor اجرا کنید (Run).
--
-- چرا امن است؟ این دستور فقط از داخل داشبورد Supabase و با دسترسی مالک پروژه
-- اجرا می‌شود. هیچ رمز یا کلیدی در کد سایت وجود ندارد و هیچ کاربر دیگری
-- نمی‌تواند نقش خودش را تغییر دهد (نگهبان دیتابیس جلوی آن را می‌گیرد).
